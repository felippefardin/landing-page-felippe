CREATE TABLE IF NOT EXISTS builder_orders (
 id CHAR(32) PRIMARY KEY,
 access_hash CHAR(64) NOT NULL,
 customer_name VARCHAR(100) NOT NULL,
 customer_cpf VARCHAR(14) NOT NULL,
 email VARCHAR(254) NOT NULL,
 project_title VARCHAR(100) NOT NULL,
 base_cents INT UNSIGNED NOT NULL,
 discount_cents INT UNSIGNED NOT NULL,
 support_cents INT UNSIGNED NOT NULL,
 total_cents INT UNSIGNED NOT NULL,
 coupon_id BIGINT UNSIGNED DEFAULT NULL,
 coupon_code VARCHAR(40) DEFAULT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'draft',
 terms_version VARCHAR(30) NOT NULL,
 terms_text MEDIUMTEXT NOT NULL,
 terms_hash CHAR(64) NOT NULL,
 signature_hash CHAR(64) DEFAULT NULL,
 signed_at DATETIME DEFAULT NULL,
 otp_hash VARCHAR(255) DEFAULT NULL,
 otp_expires DATETIME DEFAULT NULL,
 otp_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
 otp_sends TINYINT UNSIGNED NOT NULL DEFAULT 0,
 otp_last DATETIME DEFAULT NULL,
 preference_id VARCHAR(100) DEFAULT NULL,
 checkout_url TEXT DEFAULT NULL,
 payment_id VARCHAR(100) DEFAULT NULL,
 payment_status VARCHAR(32) DEFAULT NULL,
 last_check DATETIME DEFAULT NULL,
 paid_at DATETIME DEFAULT NULL,
 download_until DATETIME DEFAULT NULL,
 zip_hash CHAR(64) NOT NULL,
 downloads INT UNSIGNED NOT NULL DEFAULT 0,
 delivery_sent_at DATETIME DEFAULT NULL,
 delivery_attempts INT UNSIGNED NOT NULL DEFAULT 0,
 delivery_last DATETIME DEFAULT NULL,
 delivery_lease DATETIME DEFAULT NULL,
 support_status VARCHAR(24) NOT NULL DEFAULT 'not_requested',
 support_notified_at DATETIME DEFAULT NULL,
 support_mail_attempts INT UNSIGNED NOT NULL DEFAULT 0,
 support_mail_last DATETIME DEFAULT NULL,
 created_at DATETIME NOT NULL,
 KEY mail_queue(status,delivery_sent_at),
 KEY coupon_order(coupon_id),
 KEY created(created_at),
 UNIQUE KEY payment_unique(payment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS builder_archives (
 order_id CHAR(32) PRIMARY KEY,
 zip_data MEDIUMBLOB NOT NULL,
 purge_at DATETIME NOT NULL,
 KEY expiry(purge_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS builder_mail_jobs (
 order_id CHAR(32) PRIMARY KEY,
 sent_at DATETIME DEFAULT NULL,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 last_attempt DATETIME DEFAULT NULL,
 lease_until DATETIME DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS builder_refunds (
 order_id CHAR(32) PRIMARY KEY,
 status VARCHAR(24) NOT NULL DEFAULT 'requested',
 reason TEXT NOT NULL,
 requested_at DATETIME NOT NULL,
 deadline_at DATETIME NOT NULL,
 amount_cents INT UNSIGNED NOT NULL,
 provider_refund_id VARCHAR(100) DEFAULT NULL,
 processed_at DATETIME DEFAULT NULL,
 customer_notified_at DATETIME DEFAULT NULL,
 admin_notified_at DATETIME DEFAULT NULL,
 completed_notified_at DATETIME DEFAULT NULL,
 last_error VARCHAR(255) DEFAULT NULL,
 KEY queue(status,requested_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
